#include "pic.h"
#include "io.h"

void pic_remap(void) {
    outb(0x20, 0x11);
    outb(0xA0, 0x11);
    outb(0x21, 0x20);  /* 主片偏移 0x20 */
    outb(0xA1, 0x28);  /* 从片偏移 0x28 */
    outb(0x21, 0x04);
    outb(0xA1, 0x02);
    outb(0x21, 0x01);
    outb(0xA1, 0x01);
    outb(0x21, 0xFC);  /* 使能 IRQ0(定时器) + IRQ1(键盘) */
    outb(0xA1, 0xFF);  /* 屏蔽从片全部 */
}

void pic_send_eoi(uint8_t irq) {
    if (irq >= 8) {
        outb(0xA0, 0x20);
    }
    outb(0x20, 0x20);
}
